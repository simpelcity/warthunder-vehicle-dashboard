-- ============================================================
-- VEHICLES
-- ============================================================

create table public.vehicles (
    id text primary key,

    name text not null,

    vehicle_type_id public.vehicle_type_id not null,
    nation_id text not null,
    operator_id text,
    status_id public.vehicle_status_id not null,
    class_id public.vehicle_class_id not null,

    rank smallint not null,

    battle_rating_ab numeric(3,1) not null,
    battle_rating_rb numeric(3,1) not null,
    battle_rating_sb numeric(3,1) not null,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint vehicles_rank_check
      check (rank between 1 and 9),
    
    constraint vehicles_br_ab_check
      check (battle_rating_ab between 1.0 and 14.7),

    constraint vehicles_br_rb_check
      check (battle_rating_rb between 1.0 and 14.7),

    constraint vehicles_br_sb_check
      check (battle_rating_sb between 1.0 and 14.7)
);


