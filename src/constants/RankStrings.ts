export function getRankStrings(rank: number) {
  if (rank === 1) return 'I'
  if (rank === 2) return 'II'
  if (rank === 3) return 'III'
  if (rank === 4) return 'IV'
  if (rank === 5) return 'V'
  if (rank === 6) return 'VI'
  if (rank === 7) return 'VII'
  if (rank === 8) return 'VIII'
  if (rank === 9) return 'IX'
}